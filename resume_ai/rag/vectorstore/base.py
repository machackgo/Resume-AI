"""Bound scope is a capability supplied by trusted authentication, never query text."""
from typing import Protocol, Sequence, runtime_checkable
from ..domain import Scope
from ..embeddings.models import EmbeddingRecord
from .models import (ChunkReference, EmbeddingSpace, VectorQuery, SearchFilter,
                     StoredEmbedding, SearchHit, StoreHealth)

@runtime_checkable
class VectorStore(Protocol):
    @property
    def scope(self) -> Scope: ...
    def register_chunks(self, references: Sequence[ChunkReference]) -> None: ...
    def upsert_embeddings(self, records: Sequence[EmbeddingRecord], *, note: str = '') -> int: ...
    def get_embedding(self, embedding_id: str) -> StoredEmbedding | None: ...
    def search_vectors(self, query: VectorQuery) -> tuple[SearchHit, ...]: ...
    def count(self, space: EmbeddingSpace | None = None, filters: SearchFilter = SearchFilter()) -> int: ...
    def activate_source_version(self, source_id: str, evidence_id: str, *, expected_current: str | None) -> None: ...
    def delete_embeddings(self, embedding_ids: Sequence[str], *, purge: bool = False) -> int: ...
    def delete_source(self, source_id: str, *, purge: bool = False) -> int: ...
    def health_check(self) -> StoreHealth: ...
    def close(self) -> None: ...
